#!/usr/bin/env node
/* Generates public/assets/catalog-map.js from data/site.json:
   Magento url_key -> this site's page for that product.
   Used by public/assets/catalog.js to link the products that the LIVE
   category listing (fetched from Magento GraphQL at page load) returns.
   Runs automatically on every `npm run build` (see package.json prebuild). */
const fs = require('node:fs');
const path = require('node:path');

const site = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'site.json'), 'utf8'));

const map = {};
for (const key of Object.keys(site.products)) {
  // '/products/lighting-perth/led-downlights-perth/dl03-4kit-1.html' -> url_key 'dl03-4kit-1'
  const clean = key.endsWith('/index.html') ? key.slice(0, -'/index.html'.length) : key.replace(/\.html$/, '');
  const urlKey = clean.split('/').pop();
  const localPath = key.endsWith('/index.html')
    ? key.slice(0, -'index.html'.length)
    : key.replace(/\.html$/, '/');
  if (!map[urlKey]) map[urlKey] = localPath;
}

const out = '/* GENERATED by scripts/build-catalog-map.js on every build - do not edit.\n' +
  '   Maps a Magento product url_key to its page on this site. */\n' +
  'window.GREENHSE_CATALOG_MAP = ' + JSON.stringify(map) + ';\n';

fs.writeFileSync(path.join(__dirname, '..', 'public', 'assets', 'catalog-map.js'), out);
console.log('catalog-map.js: ' + Object.keys(map).length + ' url_key -> page entries');
